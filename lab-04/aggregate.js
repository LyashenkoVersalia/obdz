// Лабораторна робота №4. Агрегація замовлень за покупцями.
// Виконувати в MongoSH Compass після окремої команди: use dbsa
// Перед запуском має бути 10 вихідних замовлень, без тимчасового _id 11001.
// Показник orders_count відповідає запиту 6 analytic-queries.sql роботи №3.
// Додатково підсумовуємо вартість позицій, а не отримані оплати.
// $group = GROUP BY; _id задає ключ групування; $sum = агрегування;
// $sum: 1 рахує документи, $sum: "$order_value" додає значення поля;
// $sort = ORDER BY; -1 означає спадання, 1 — зростання.
// Фактично отримано 4 групи: customer01 — 3 / 11090.00;
// customer02 — 3 / 2250.00; customer03 — 2 / 7220.00;
// customer04 — 2 / 3640.00. Загалом 10 замовлень / 24200.00 грн.
// customer05 без замовлень не має документа події й не створить групу.

db.orders.aggregate([
  {
    $group: {
      _id: "$customer.email",
      orders_count: { $sum: 1 },
      order_value: { $sum: "$order_value" }
    }
  },
  {
    $sort: { orders_count: -1, _id: 1 }
  }
]).toArray();
